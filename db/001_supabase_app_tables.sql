-- Estructuras base que faltan cuando Supabase se inicializó con el esquema
-- resumido de contexto (sin usuario/roles, auditoría ni datos de empresa).
-- Ejecutar una sola vez antes de db/002_operational_controls.sql.
-- Es aditiva e idempotente: no elimina ni reemplaza tablas o registros.

BEGIN;

CREATE TABLE IF NOT EXISTS public.rol (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo varchar(30) NOT NULL UNIQUE,
    nombre varchar(100) NOT NULL,
    descripcion varchar(255),
    activo boolean NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS public.permiso (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo varchar(50) NOT NULL UNIQUE,
    nombre varchar(100) NOT NULL,
    modulo varchar(30) NOT NULL,
    accion varchar(20) NOT NULL,
    descripcion varchar(255)
);

CREATE TABLE IF NOT EXISTS public.usuario (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username varchar(50) NOT NULL UNIQUE,
    email varchar(100) NOT NULL UNIQUE,
    password_hash varchar(255) NOT NULL,
    nombre_completo varchar(150) NOT NULL,
    activo boolean NOT NULL DEFAULT true,
    fecha_creacion timestamp without time zone NOT NULL DEFAULT now(),
    ultimo_acceso timestamp without time zone,
    sucursal_id integer REFERENCES public.sucursal(id)
);

CREATE TABLE IF NOT EXISTS public.usuario_rol (
    usuario_id integer NOT NULL REFERENCES public.usuario(id),
    rol_id integer NOT NULL REFERENCES public.rol(id),
    PRIMARY KEY (usuario_id, rol_id)
);

CREATE TABLE IF NOT EXISTS public.rol_permiso (
    rol_id integer NOT NULL REFERENCES public.rol(id),
    permiso_id integer NOT NULL REFERENCES public.permiso(id),
    PRIMARY KEY (rol_id, permiso_id)
);

CREATE TABLE IF NOT EXISTS public.empresa (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    razon_social varchar(150) NOT NULL,
    nombre_comercial varchar(100) NOT NULL,
    nit varchar(20),
    nrc varchar(20),
    giro text
);

CREATE TABLE IF NOT EXISTS public.auditoria (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha timestamp without time zone NOT NULL DEFAULT now(),
    usuario_id integer REFERENCES public.usuario(id) ON DELETE SET NULL,
    usuario_nombre varchar(150) NOT NULL,
    modulo varchar(30) NOT NULL,
    entidad varchar(30) NOT NULL,
    registro_id integer,
    registro_codigo varchar(40),
    accion varchar(20) NOT NULL,
    descripcion text,
    datos_antes text,
    datos_despues text,
    ip varchar(45)
);

CREATE INDEX IF NOT EXISTS idx_auditoria_fecha
    ON public.auditoria(fecha);
CREATE INDEX IF NOT EXISTS idx_auditoria_modulo_accion
    ON public.auditoria(modulo, accion);
CREATE INDEX IF NOT EXISTS idx_auditoria_usuario
    ON public.auditoria(usuario_id);
CREATE INDEX IF NOT EXISTS idx_auditoria_registro
    ON public.auditoria(entidad, registro_id);
CREATE INDEX IF NOT EXISTS idx_usuario_sucursal
    ON public.usuario(sucursal_id);

COMMIT;
