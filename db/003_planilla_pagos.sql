-- Registra el desembolso de una planilla como asiento contable separado.
-- Se puede volver a ejecutar sin duplicar la tabla.
CREATE TABLE IF NOT EXISTS public.planilla_pago (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    planilla_id integer NOT NULL REFERENCES public.planilla(id) ON DELETE RESTRICT,
    asiento_id integer NOT NULL UNIQUE REFERENCES public.asiento(id) ON DELETE RESTRICT,
    fecha_pago date NOT NULL,
    periodo_id integer NOT NULL REFERENCES public.periodo_contable(id),
    cuenta_pago_codigo character varying(20) NOT NULL REFERENCES public.catalogo_cuenta(codigo),
    monto numeric(14,2) NOT NULL CHECK (monto > 0),
    estado character varying(20) NOT NULL DEFAULT 'PENDIENTE'
        CHECK (estado IN ('PENDIENTE','PAGADA')),
    creado_por integer REFERENCES public.usuario(id) ON DELETE SET NULL,
    creado_en timestamp without time zone NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_planilla_pago_planilla ON public.planilla_pago(planilla_id);
